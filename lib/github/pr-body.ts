import type { PullRequestProposal, ValidationCheck } from "@/types";

export function buildPullRequest(input: {
  dependency: string;
  fromVersion: string;
  toVersion: string;
  files: { path: string; edits: string[] }[];
  confidence: number;
  checks: ValidationCheck[];
  simulated: boolean;
  blocked: boolean;
  reviewRequired: boolean;
  base?: string;
  number?: number | null;
  url?: string | null;
}): PullRequestProposal {
  const branch = `apisync/${input.dependency}-sdk-migration`;
  const base = input.base ?? "main";
  const title = `chore: migrate ${displayName(input.dependency)} SDK usage`;
  const fileLines = input.files.map((file) => `- ${file.path}: ${file.edits.join("; ") || "updated"}`);
  const validationLines = input.checks.map((check) => {
    const mark = check.status === "passed" ? "✓" : check.status === "failed" ? "✕" : "–";
    return `${mark} ${check.label}`;
  });

  const body = [
    "## ApiSync AI Migration",
    "",
    "Detected breaking change:",
    `${displayName(input.dependency)} SDK ${input.toVersion}`,
    "",
    "### Why",
    "",
    `The ${input.fromVersion} → ${input.toVersion} upgrade changes call structure. ApiSync rewrote only AST patterns that matched a vetted rule.`,
    "",
    "### Changes",
    "",
    ...fileLines,
    "",
    "### Validation",
    "",
    ...validationLines,
    "",
    "### Confidence",
    "",
    `${Math.round(input.confidence * 100)}%`,
    "",
    input.reviewRequired ? "Review required before merge. Confidence is below the automatic-proposal threshold." : "Confidence is high enough to propose automatically. Merge stays manual.",
    "",
    input.simulated ? "This pull request was simulated in demo mode and was not opened on GitHub." : "Generated by ApiSync AI. This pull request is not merged automatically.",
  ].join("\n");

  return {
    number: input.blocked ? null : (input.number ?? null),
    title,
    body,
    branch,
    base,
    status: input.blocked ? "blocked" : input.simulated || input.url || input.number ? "open" : "not_created",
    simulated: input.simulated,
    url: input.url ?? null,
    reviewRequired: input.reviewRequired,
  };
}

function displayName(value: string) {
  const known: Record<string, string> = {
    openai: "OpenAI",
    stripe: "Stripe",
    twilio: "Twilio",
  };
  return known[value] ?? value.slice(0, 1).toUpperCase() + value.slice(1);
}
